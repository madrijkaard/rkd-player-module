const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const root = path.resolve(__dirname, '..');
const testRoot = path.resolve(process.env.LUMEN_TEST_DIR || path.join(root, 'test-results'));
fs.mkdirSync(testRoot, { recursive: true });
const dataDir = fs.mkdtempSync(path.join(testRoot, 'recommendations-'));
const initialId = 'M7lc1UVf-VE', channelId = 'UC_x5XG1OV2P6uZZ5FSM9Ttw';
fs.writeFileSync(path.join(dataDir, 'library.json'), JSON.stringify({ version: 2, library: [{ id: initialId, title: 'YouTube API Demo', author: 'Google for Developers' }], settings: { mode: 'library', transparency: 0 } }));
const env = { ...process.env, LUMEN_DATA_DIR: dataDir, NODE_USE_SYSTEM_CA: '1' };
delete env.ELECTRON_RUN_AS_NODE;
let app, page;
const errors = [];
async function launch() {
  app = await electron.launch({ args: [root, '--test'], env, timeout: 30000 });
  page = await app.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  await page.waitForFunction(() => document.body.dataset.ready === 'true');
}
(async () => {
  try {
    await launch();
    await page.locator('#library-dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#recommendations').isVisible(), true);
    assert.match(await page.locator('#recommendations-status').innerText(), /Selecione/);
    await page.locator('#library-button').click();
    await page.locator('.card-play').waitFor({ timeout: 45000 });
    await page.locator('.card-play').click();
    await page.locator('#library-dialog').waitFor({ state: 'hidden' });
    await page.locator('.recommendation-card').first().waitFor({ timeout: 45000 });
    const cards = await page.locator('.recommendation-card').evaluateAll(nodes => nodes.map(n => ({ id: n.dataset.id, channel: n.dataset.channelId })));
    assert.ok(cards.length > 1);
    assert.ok(cards.every(v => v.channel === channelId));
    await page.waitForFunction(() => document.querySelector('.recommendation-card img').naturalWidth > 0);
    assert.equal(await page.locator('#player').getAttribute('src'), null);
    assert.equal(await page.locator('#player').isVisible(), false);
    await page.locator('.recommendation-card').first().click();
    await page.waitForFunction(() => document.querySelector('#video-label').textContent.includes('REPRODUZINDO'), null, { timeout: 45000 });
    await page.waitForFunction(() => document.querySelector('#recommendations').getAttribute('aria-busy') === 'false', null, { timeout: 45000 });
    await page.screenshot({ path: path.join(testRoot, 'recommended.png') });
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 620));
    await page.waitForFunction(() => innerWidth === 900);
    const layout = await page.evaluate(() => {
      const rect = s => { const r = document.querySelector(s).getBoundingClientRect(); return { left: r.left, right: r.right, top: r.top, bottom: r.bottom }; };
      return { library: rect('#library-button'), carousel: rect('#recommendations'), settings: rect('#settings-button'), stage: rect('#stage'), width: innerWidth, scrollWidth: document.documentElement.scrollWidth };
    });
    assert.ok(layout.library.right <= layout.settings.left);
    assert.ok(layout.settings.top > layout.stage.top);
    assert.ok(layout.carousel.bottom <= layout.stage.top);
    assert.ok(layout.settings.right <= layout.width && layout.scrollWidth <= layout.width);
    await page.locator('#recommendations-next').click();
    await page.waitForFunction(() => document.querySelector('#recommendations-track').scrollLeft > 100);
    await page.screenshot({ path: path.join(testRoot, 'recommended-small.png') });
    console.log('PASS vídeos reais do mesmo canal, miniaturas, reprodução e carrossel horizontal em 900px.');
    const beforeRefresh = await page.locator('.recommendation-card').evaluateAll(nodes => nodes.map(node => node.dataset.id));
    const chosen = await page.locator('.recommendation-card').first().getAttribute('data-id');
    await page.locator(`.recommendation-card[data-id="${chosen}"]`).click();
    await page.waitForFunction(id => document.querySelector('#player').src.includes(`video=${id}`), chosen);
    await page.waitForFunction(() => document.querySelector('#recommendations').getAttribute('aria-busy') === 'false');
    assert.equal(await page.locator(`.recommendation-card[data-id="${chosen}"]`).count(), 0);
    const afterRefresh = await page.locator('.recommendation-card').evaluateAll(nodes => nodes.map(node => node.dataset.id));
    assert.notDeepEqual(afterRefresh, beforeRefresh);
    assert.ok(!afterRefresh.includes(chosen));
    assert.ok((await page.locator('.recommendation-card').evaluateAll(nodes => nodes.map(node => node.dataset.channelId))).every(id => id === channelId));
    console.log('PASS novo sorteio após clique, excluindo o vídeo atual e mantendo o canal.');
    await page.screenshot({ path: path.join(testRoot, 'save-recommendation.png') });
    const saved = JSON.parse(fs.readFileSync(path.join(dataDir, 'library.json'), 'utf8'));
    assert.equal(saved.library.length, 1);
    assert.equal(saved.library[0].id, channelId);
    assert.equal(saved.legacyVideos.length, 0);
    await page.waitForFunction(() => document.querySelector('#video-label').textContent.includes('REPRODUZINDO'), null, { timeout: 45000 });
    const source = await page.locator('#player').getAttribute('src');
    const initial = await page.evaluate(() => window.lumen.init());
    const wrapper = page.frames().find(frame => frame.url().startsWith(initial.playerOrigin));
    const before = await wrapper.evaluate(() => player.getCurrentTime());
    await page.locator('#library-button').click();
    await page.locator('.card-play').click();
    assert.equal(await page.locator('#player').getAttribute('src'), source);
    assert.equal(await page.locator('#player').isVisible(), true);
    await page.locator('.recommendation-card').first().waitFor();
    await wrapper.waitForFunction(before => player.getPlayerState() === 1 && player.getCurrentTime() > before + 2, before);
    console.log('PASS seleção na biblioteca preserva o player e a reprodução real continua avançando.');
    await page.locator('#settings-button').click();
    assert.equal(await page.locator('#settings-dialog').evaluate(el => el.open), true);
    await page.locator('#settings-dialog .primary').click();
    assert.equal(await page.locator('#stop-video, #open-youtube').count(), 0);
    await app.close(); app = null;
    await launch();
    await page.locator('#library-dialog').waitFor({ state: 'hidden' });
    assert.equal(await page.locator('#recommendations').isVisible(), true);
    assert.equal(await page.locator('.video-card').count(), 1);
    assert.deepEqual(errors, []);
    console.log('PASS migração para canal, seleção sem autoplay, reprodução pelo carrossel e persistência sem salvar vídeos.');
    fs.writeFileSync(path.join(testRoot, 'recommendations-live-test.json'), JSON.stringify({ passed: true, cards, layout, errors }, null, 2));
  } catch (error) {
    console.error(error);
    if (page && !page.isClosed()) await page.screenshot({ path: path.join(testRoot, 'recommendations-failure.png') }).catch(() => {});
    process.exitCode = 1;
  } finally { await app?.close().catch(() => {}); }
})();
