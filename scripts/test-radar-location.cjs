const { _electron: electron } = require('playwright');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..'), out = path.resolve(process.env.LUMEN_TEST_DIR || path.join(root, 'test-results'));
fs.mkdirSync(out, { recursive: true }); const data = fs.mkdtempSync(path.join(out, 'radar-location-'));
fs.writeFileSync(path.join(data, 'library.json'), JSON.stringify({ settings: { theme: 'military', visualizerEnabled: false } }));
const bootstrap = path.join(data, 'bootstrap.cjs');
// Fixtures replace only Windows location and flight transport; app IPC/rendering are real.
fs.writeFileSync(bootstrap, `
const cp=require('node:child_process'),original=cp.execFile;
global.geo={status:'available',lat:40.4,lon:-3.7,accuracy:1000};global.offset=0;global.geoCalls=0;
const realNow=Date.now;Date.now=()=>realNow()+global.offset;
cp.execFile=(exe,args,options,callback)=>{if(!String(exe).endsWith('powershell.exe'))return original(exe,args,options,callback);global.geoCalls++;const timer=setTimeout(()=>callback(null,JSON.stringify(global.geo)),10);return {kill(){clearTimeout(timer);callback(Error('Cancelled'),'');}};};
global.fetch=async url=>{global.lastRadarUrl=String(url);const t=Math.floor(Date.now()/1000);return Response.json({time:t,states:geo.status==='available'?[['abcdef','TEST123','Test',t,t,geo.lon+.1,geo.lat+.1,9000,false,200,90]]:[]});};
require(${JSON.stringify(path.join(root, 'src', 'main.cjs'))});
`);
const env = { ...process.env, LUMEN_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
(async () => { let app; try {
  app = await electron.launch({ args: [bootstrap, '--test'], env }); const page = await app.firstWindow();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.waitForFunction(() => document.body.dataset.ready === 'true');
  await page.locator('#radar-background[data-state="live"]').waitFor();
  assert.equal(await app.evaluate(() => global.geoCalls), 1);
  let snapshot = await page.evaluate(() => window.lumen.radar()); assert.equal(snapshot.location.lat, 40.4); assert.equal(snapshot.bounds.west, -6.7);
  await page.locator('#settings-button').click();
  assert.equal(await page.locator('#radar-location-setting').count(), 0);
  assert.equal(await page.locator('#radar-status').isVisible(), false);
  await page.locator('#settings-dialog').evaluate(async n => Promise.all(n.getAnimations().map(a => a.finished)));
  await page.screenshot({ path: path.join(out, 'location-available.png') });
  await app.evaluate(() => { global.geo = { status: 'available', lat: -33.8, lon: 151.2, accuracy: 2000 }; global.offset += 660000; });
  snapshot = await page.evaluate(() => window.lumen.radar());
  assert.equal(snapshot.location.lat, 40.4); assert.equal(await app.evaluate(() => global.geoCalls), 1);
  await page.locator('#theme').selectOption('cyberpunk');
  await page.locator('#theme').selectOption('military');
  await page.waitForFunction(async () => (await window.lumen.radar()).location?.lat === -33.8);
  await app.evaluate(() => { global.offset += 61000; });
  snapshot = await page.evaluate(() => window.lumen.radar()); assert.equal(snapshot.bounds.west, 148.2); assert.ok(Math.abs(snapshot.flights[0].lat + 33.7) < 1e-8);
  assert.equal(await app.evaluate(() => global.geoCalls), 2);
  await app.evaluate(({ BrowserWindow }) => { const win=BrowserWindow.getAllWindows()[0]; win.show(); win.minimize(); });
  await page.waitForFunction(() => document.querySelector('#radar-background').hidden);
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].restore());
  await page.waitForFunction(() => !document.querySelector('#radar-background').hidden);
  await page.evaluate(() => window.lumen.radar());
  assert.equal(await app.evaluate(() => global.geoCalls), 2);
  await app.evaluate(() => { global.geo = { status: 'denied' }; });
  await page.locator('#theme').selectOption('cyberpunk');
  await page.locator('#theme').selectOption('military');
  await page.waitForFunction(async () => (await window.lumen.radar()).location?.status === 'denied');
  assert.equal(await app.evaluate(() => global.geoCalls), 3);
  await page.screenshot({ path: path.join(out, 'location-denied.png') });
  await page.locator('#theme').selectOption('space');
  await page.waitForFunction(async () => (await window.lumen.radar()).status === 'inactive');
  assert.equal(await page.evaluate(() => typeof window.lumen.locateRadar), 'undefined');
  assert.deepEqual(errors, []);
  assert.equal(fs.readFileSync(path.join(data, 'library.json'), 'utf8').includes('151.2'), false);
  console.log('PASS location at startup and Radar selection only, no periodic or minimize/restore lookup, recentering, denied fallback, removed settings section and no coordinates on disk (fixtures).');
} catch (e) { console.error(e); process.exitCode = 1; } finally { await app?.close(); } })();
